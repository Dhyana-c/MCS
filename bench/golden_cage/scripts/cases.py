def build_cases() -> list[dict]:
    """展开为统一结构：query/answer/question_type/evidence。"""
    cases = []
    for c in INFERENCE_CASES:
        cases.append({**c, "question_type": "inference_query"})
    for c in COMPARISON_CASES:
        cases.append({**c, "question_type": "comparison_query"})
    for c in TEMPORAL_CASES:
        cases.append({**c, "question_type": "temporal_query"})
    for q in NULL_CASES:
        cases.append(
            {
                "query": q,
                "answer": "Insufficient information.",
                "question_type": "null_query",
                "evidence": [],
            }
        )
    return cases
